function resolveContained(base, path) {
  const resolvedBase = resolve(base)
  const resolvedPath = resolve(resolvedBase, path)
  if (resolvedPath === resolvedBase || !resolvedPath.startsWith(`${resolvedBase}${sep}`)) {
    throw new Error(`generated path escapes its output directory: ${path}`)
  }
  return resolvedPath
}

