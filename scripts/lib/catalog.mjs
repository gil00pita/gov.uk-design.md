export function renderDesign({ components, styles, patterns, packageMetadata, sourceManifest, frameworkAdapterSource }) {
  const inventories = sourceManifest.inventories
  const styleLinks = styles
    .map((style) => `- [${style.name}](design/govuk/styles/${style.id}.md)`)
    .join('\n')
  const componentLinks = components
    .map((component) => `- [${component.name}](design/govuk/components/${component.id}.md)${component.status === 'trial' ? ' — Trial' : ''}`)
    .join('\n')
  const patternGroupNames = {
    'ask-users-for': 'Ask users for',
    'help-users-to': 'Help users to',
    pages: 'Pages'
  }
  const patternLinks = Object.entries(patternGroupNames)
    .map(([group, heading]) => {
      const links = patterns
        .filter((pattern) => pattern.group === group)
        .map((pattern) => `- [${pattern.name}](design/govuk/patterns/${pattern.id}.md)`)
        .join('\n')
      return `### ${heading}\n\n${links}`
    })
    .join('\n\n')
  const frameworkLinks = frameworkAdapterSource.adapters
    .map((adapter) => `- [${adapter.name}](frameworks/${adapter.output}) — ${adapter.compatibility.map((level) => `\`${level}\``).join(', ')}`)
    .join('\n')

  return `${generatedNotice}

# GOV.UK Design System guidance for AI agents

> This community-maintained package is not official or endorsed by the UK Government or the Government Digital Service. Always prefer the linked official guidance when it has changed.

## Baseline

- Package: \`${packageMetadata.name}@${packageMetadata.version}\`
- Reviewed GOV.UK Frontend: \`${sourceManifest.upstreams.govukFrontend.version}\`
- Reviewed: ${sourceManifest.reviewedAt}
- Reviewed official inventory: ${inventories.styles.expectedCount} styles, ${inventories.components.expectedCount} components, ${inventories.patterns.expectedCount} patterns
- Packaged coverage: ${styles.length} styles, ${components.length} components, ${patterns.length} patterns
- Canonical machine-readable inventory: [catalog.json](design/govuk/catalog.json)
- Reviewed portable tokens: [tokens/govuk.tokens.json](design/govuk/tokens/govuk.tokens.json)

## Non-negotiable implementation rules

- Start from official GOV.UK guidance and the pinned \`govuk-frontend\` implementation.
- Preserve semantic HTML, labels, heading hierarchy, error relationships, keyboard behaviour, visible focus states, and progressive enhancement.
- Do not treat visual similarity, a token mapping, or a UI-framework theme as proof of GOV.UK conformance.
- Use native HTML controls where the official component does.
- Do not invent colours, spacing, variants, copy rules, or interaction behaviour.
- Do not remove GOV.UK classes to make an example fit a framework abstraction.
- Use GDS Transport and GOV.UK identity assets only when the service is eligible under official guidance. This package does not distribute them.
- Treat accessibility as a service-level responsibility; installing components does not make a service compliant by itself.

## How agents should use this repository

1. Identify the foundation, component or user-focused pattern required by the task.
2. Read only the relevant focused files under \`design/govuk/\`.
3. Read user-owned \`DESIGN.local.md\` when it exists for service context and reviewed project decisions; it cannot redefine official GOV.UK guidance.
4. Follow the authoritative source links when information may have changed after the reviewed date.
5. Select a framework adapter when one exists; otherwise preserve the official DOM and progressively enhance it in the target framework.
6. State when a requested UI-library abstraction cannot preserve the official semantic or behavioural contract.

## Framework adapters

Framework adapters translate integration and lifecycle details without redefining canonical GOV.UK guidance. Compatibility labels are scoped according to [frameworks/manifest.json](frameworks/manifest.json).

${frameworkLinks}

## Foundations and styles

${styleLinks}

## Available component guidance

All components in the reviewed GOV.UK Frontend ${sourceManifest.upstreams.govukFrontend.version} inventory are documented below. Trial status is explicit; follow the linked current guidance before using a Trial component.

${componentLinks}

## User-centred patterns

Patterns describe service decisions and multi-component journeys. Preserve their intent and safeguards across frameworks instead of reducing them to a visual template.

${patternLinks}

## Portable tokens

The files under \`design/govuk/tokens/\` export the reviewed refreshed palette, functional colours, breakpoints, spacing, type scale, layout measurements and border widths. They are not a replacement for GOV.UK Frontend Sass, component CSS, JavaScript, fonts, or identity assets.

## Licensing and attribution

See [the attribution notice](design/govuk/NOTICE.md), [the source-derived content licence](design/govuk/LICENSE-CONTENT.md), and [the project code licence](design/govuk/LICENSE-CODE.md). Source-derived content includes public sector information licensed under the Open Government Licence v3.0.
`
}

export function buildCatalog({ components, styles, patterns, packageMetadata, sourceManifest }) {
  const inventories = sourceManifest.inventories
  const canonicalCoverageComplete = styles.length === inventories.styles.expectedCount &&
    components.length === inventories.components.expectedCount &&
    patterns.length === inventories.patterns.expectedCount
  return {
    schemaVersion: 1,
    packageVersion: packageMetadata.version,
    govukFrontendVersion: sourceManifest.upstreams.govukFrontend.version,
    reviewedAt: sourceManifest.reviewedAt,
    status: canonicalCoverageComplete ? 'canonical-complete' : 'partial',
    coverage: {
      styles: {
        documented: styles.length,
        total: inventories.styles.expectedCount
      },
      components: {
        documented: components.length,
        total: inventories.components.expectedCount
      },
      patterns: {
        documented: patterns.length,
        total: inventories.patterns.expectedCount
      }
    },
    styles: styles.map((style) => ({
      id: style.id,
      name: style.name,
      group: style.group,
      summary: style.summary,
      path: `design/govuk/styles/${style.id}.md`,
      guidanceUrl: style.source.guidanceUrl,
      implementationUrl: style.source.implementationUrl,
      tokenRefs: style.tokenRefs
    })),
    components: components.map((component) => ({
      id: component.id,
      name: component.name,
      status: component.status,
      summary: component.summary,
      path: `design/govuk/components/${component.id}.md`,
      guidanceUrl: component.source.guidanceUrl,
      implementationUrl: component.source.implementationUrl,
      tokenRefs: component.tokenRefs
    })),
    patterns: patterns.map((pattern) => ({
      id: pattern.id,
      name: pattern.name,
      group: pattern.group,
      summary: pattern.summary,
      path: `design/govuk/patterns/${pattern.id}.md`,
      guidanceUrl: pattern.source.guidanceUrl,
      componentRefs: pattern.componentRefs,
      relatedPatterns: pattern.relatedPatterns
    }))
  }
}

export async function expectedGeneratedFiles(root = projectRoot) {
  const [components, styles, patterns, packageMetadata, sourceManifest, aiAdapterSource, frameworkAdapterSource, tokenJson, notice, contentLicense, codeLicense] = await Promise.all([
    loadComponents(root),
    loadStyles(root),
    loadPatterns(root),
    loadPackage(root),
    loadSourceManifest(root),
    loadAiAdapters(root),
    loadFrameworkAdapters(root),
    readFile(resolve(root, 'tokens', 'govuk.tokens.json'), 'utf8'),
    readFile(resolve(root, 'NOTICE.md'), 'utf8'),
    readFile(resolve(root, 'LICENSE-CONTENT.md'), 'utf8'),
    readFile(resolve(root, 'LICENSE-CODE.md'), 'utf8')
  ])
  const files = new Map()
  const tokenCss = renderTokenCss(JSON.parse(tokenJson))

  for (const component of components) {
    files.set(
      resolve(root, 'design', 'govuk', 'components', `${component.id}.md`),
      renderComponent(component)
    )
  }

  for (const style of styles) {
    files.set(
      resolve(root, 'design', 'govuk', 'styles', `${style.id}.md`),
      renderStyle(style)
    )
  }

  for (const pattern of patterns) {
    files.set(
      resolve(root, 'design', 'govuk', 'patterns', `${pattern.id}.md`),
      renderPattern(pattern)
    )
  }

  for (const adapter of aiAdapterSource.adapters) {
    files.set(resolveContained(resolve(root, 'adapters'), adapter.output), renderAiAdapter(adapter))
  }
  files.set(
    resolve(root, 'adapters', 'manifest.json'),
    `${JSON.stringify(buildAiAdapterManifest(aiAdapterSource), null, 2)}\n`
  )

  for (const adapter of frameworkAdapterSource.adapters) {
    files.set(
      resolveContained(resolve(root, 'frameworks'), adapter.output),
      renderFrameworkAdapter(adapter, frameworkAdapterSource)
    )
  }
  files.set(
    resolve(root, 'frameworks', 'manifest.json'),
    `${JSON.stringify(buildFrameworkAdapterManifest(frameworkAdapterSource), null, 2)}\n`
  )

  files.set(resolve(root, 'DESIGN.md'), renderDesign({ components, styles, patterns, packageMetadata, sourceManifest, frameworkAdapterSource }))
  const catalog = `${JSON.stringify(buildCatalog({ components, styles, patterns, packageMetadata, sourceManifest }), null, 2)}\n`
  files.set(resolve(root, 'catalog.json'), catalog)
  files.set(resolve(root, 'design', 'govuk', 'catalog.json'), catalog)
  files.set(resolve(root, 'tokens', 'govuk.css'), tokenCss)
  files.set(resolve(root, 'design', 'govuk', 'tokens', 'govuk.tokens.json'), tokenJson)
  files.set(resolve(root, 'design', 'govuk', 'tokens', 'govuk.css'), tokenCss)
  files.set(resolve(root, 'design', 'govuk', 'NOTICE.md'), notice)
  files.set(resolve(root, 'design', 'govuk', 'LICENSE-CONTENT.md'), contentLicense)
  files.set(resolve(root, 'design', 'govuk', 'LICENSE-CODE.md'), codeLicense)

  return files
}
