function remFromPixels(token) {
  const value = token?.$value
  if (!value || value.unit !== 'px' || !Number.isFinite(value.value)) {
    throw new Error(`Tailwind breakpoint token must be a pixel dimension: ${JSON.stringify(token)}`)
  }
  return `${Number((value.value / 16).toFixed(4))}rem`
}

export function renderTailwindTheme(tokens, {
  description = 'This Tailwind CSS 4 bridge is for service-owned extensions, not component recreation.'
} = {}) {
  const govuk = tokens.govuk
  const declarations = []
  const palette = govuk.color.palette

  for (const [name, value] of Object.entries(palette)) {
    if ('$value' in value) {
      declarations.push(`  --color-govuk-${name}: var(--govuk-color-palette-${name});`)
      continue
    }
    for (const tokenName of Object.keys(value).filter((key) => !key.startsWith('$'))) {
      const suffix = tokenName === 'primary' ? '' : `-${tokenName}`
      declarations.push(`  --color-govuk-${name}${suffix}: var(--govuk-color-palette-${name}-${tokenName});`)
    }
  }

  for (const name of Object.keys(govuk.color).filter((key) => !key.startsWith('$') && key !== 'palette')) {
    declarations.push(`  --color-govuk-${name}: var(--govuk-color-${name});`)
  }
  declarations.push('  --color-govuk-background: var(--govuk-color-body-background);')
  declarations.push('  --color-govuk-surface: var(--govuk-color-surface-background);')

  for (const name of Object.keys(govuk.spacing.static).filter((key) => !key.startsWith('$'))) {
    declarations.push(`  --spacing-govuk-${name}: var(--govuk-spacing-static-${name});`)
  }
  for (const name of Object.keys(govuk.spacing.responsive).filter((key) => !key.startsWith('$'))) {
    declarations.push(`  --spacing-govuk-responsive-${name}: var(--govuk-spacing-responsive-${name});`)
  }
  declarations.push('  --spacing-govuk-gutter: var(--govuk-page-gutter);')

  for (const name of Object.keys(govuk.typography.scale).filter((key) => !key.startsWith('$'))) {
    declarations.push(`  --text-govuk-${name}: var(--govuk-font-size-${name});`)
    declarations.push(`  --text-govuk-${name}--line-height: var(--govuk-line-height-${name});`)
  }
  for (const name of Object.keys(govuk.typography.weight).filter((key) => !key.startsWith('$'))) {
    declarations.push(`  --font-weight-govuk-${name}: var(--govuk-typography-weight-${name});`)
  }

  for (const [name, token] of Object.entries(govuk.breakpoint).filter(([key]) => !key.startsWith('$'))) {
    declarations.push(`  --breakpoint-govuk-${name}: ${remFromPixels(token)};`)
  }
  declarations.push('  --container-govuk-page: var(--govuk-layout-page-width);')

  return `/*
 * Generated from the reviewed GOV.UK Frontend ${tokens.$extensions?.['org.govuk-design-md.provenance']?.govukFrontendVersion ?? 'unknown'} token source.
 * ${description}
 * Keep the canonical token file at the relative path below or update the import.
 */
@import "../../design/govuk/tokens/govuk.css";

@theme static {
${declarations.join('\n')}
}
`
}

