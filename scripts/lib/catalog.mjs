export async function loadComponents(root = projectRoot) {
  const directory = resolve(root, 'src', 'catalog', 'components')
  const filenames = (await readdir(directory))
    .filter((filename) => filename.endsWith('.json'))
    .sort()

  const components = await Promise.all(
    filenames.map((filename) => readJson(resolve(directory, filename)))
  )

  return components.sort((left, right) => left.name.localeCompare(right.name, 'en-GB'))
}

