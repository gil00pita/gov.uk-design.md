export function renderChakraSystem(tokens) {
  const govuk = tokens.govuk
  const palette = []
  for (const [name, value] of Object.entries(govuk.color.palette)) {
    if ('$value' in value) {
      palette.push([`govuk-${name}`, `var(--govuk-color-palette-${name})`])
      continue
    }
    for (const tokenName of Object.keys(value).filter((key) => !key.startsWith('$'))) {
      const suffix = tokenName === 'primary' ? '' : `-${tokenName}`
      palette.push([`govuk-${name}${suffix}`, `var(--govuk-color-palette-${name}-${tokenName})`])
    }
  }

  const functionalColors = Object.keys(govuk.color)
    .filter((key) => !key.startsWith('$') && key !== 'palette')
    .map((name) => [`govuk-${name}`, `var(--govuk-color-${name})`])
  functionalColors.push(['govuk-background', 'var(--govuk-color-body-background)'])
  functionalColors.push(['govuk-surface', 'var(--govuk-color-surface-background)'])

  const spacing = Object.keys(govuk.spacing.static)
    .filter((key) => !key.startsWith('$'))
    .map((name) => [`govuk-${name}`, `var(--govuk-spacing-static-${name})`])
  for (const name of Object.keys(govuk.spacing.responsive).filter((key) => !key.startsWith('$'))) {
    spacing.push([`govuk-responsive-${name}`, `var(--govuk-spacing-responsive-${name})`])
  }
  spacing.push(['govuk-gutter', 'var(--govuk-page-gutter)'])

  const fontSizes = Object.keys(govuk.typography.scale)
    .filter((key) => !key.startsWith('$'))
    .map((name) => [`govuk-${name}`, `var(--govuk-font-size-${name})`])
  const lineHeights = Object.keys(govuk.typography.scale)
    .filter((key) => !key.startsWith('$'))
    .map((name) => [`govuk-${name}`, `var(--govuk-line-height-${name})`])
  const fontWeights = Object.keys(govuk.typography.weight)
    .filter((key) => !key.startsWith('$'))
    .map((name) => [`govuk-${name}`, `var(--govuk-typography-weight-${name})`])
  const borderWidths = Object.keys(govuk.border)
    .filter((key) => !key.startsWith('$'))
    .map((name) => [`govuk-${name}`, `var(--govuk-border-${name})`])
  const breakpoints = Object.entries(govuk.breakpoint)
    .filter(([key]) => !key.startsWith('$'))
    .map(([name, token]) => [`govuk-${name}`, `${token.$value.value}${token.$value.unit}`])

  return `/*
 * Generated from the reviewed GOV.UK Frontend ${tokens.$extensions?.['org.govuk-design-md.provenance']?.govukFrontendVersion ?? 'unknown'} token source.
 * This reset-free Chakra UI 3 system is for service-owned extensions, not component recreation.
 * Load design/govuk/tokens/govuk.css before rendering components that consume these values.
 */
import { createSystem, defaultBaseConfig, defineConfig } from '@chakra-ui/react'

const govukChakraConfig = defineConfig({
  cssVarsPrefix: 'govuk-chakra',
  disableLayers: true,
  preflight: false,
  globalCss: {},
  theme: {
    breakpoints: {
${renderChakraValues(breakpoints)}
    },
    tokens: {
      colors: {
${renderChakraTokens([...palette, ...functionalColors])}
      },
      spacing: {
${renderChakraTokens(spacing)}
      },
      sizes: {
        "govuk-page": { value: "var(--govuk-layout-page-width)" }
      },
      fontSizes: {
${renderChakraTokens(fontSizes)}
      },
      lineHeights: {
${renderChakraTokens(lineHeights)}
      },
      fontWeights: {
${renderChakraTokens(fontWeights)}
      },
      borderWidths: {
${renderChakraTokens(borderWidths)}
      }
    }
  }
})

export const govukChakraSystem = createSystem(defaultBaseConfig, govukChakraConfig)
`
}

export function renderComponent(component) {
  const anatomy = component.anatomy
    .map((item) => `- **${item.name}${item.required ? ' (required)' : ''}:** ${item.description}`)
    .join('\n')
  const variants = component.variants
    .map((variant) => `| ${variant.name} | \`${variant.element}\` | ${inlineCodeList(variant.classes)} | ${variant.use} |`)
    .join('\n')
  const examples = component.htmlExamples
    .map((example) => `### ${example.name}\n\n\`\`\`html\n${example.html}\n\`\`\``)
    .join('\n\n')

  return `${generatedNotice}

# ${component.name}

**Status:** ${component.status[0].toUpperCase()}${component.status.slice(1)}  
**Reviewed against:** GOV.UK Frontend ${component.source.govukFrontendVersion} on ${component.source.reviewedAt}

${component.summary}

## When to use

${bullets(component.whenToUse)}

## When not to use

${bullets(component.whenNotToUse)}

## Anatomy

${anatomy}

## Variants

| Variant | Element | Classes | Use |
| --- | --- | --- | --- |
${variants}

## Behaviour and progressive enhancement

${bullets(component.behaviour)}

## Accessibility contract

${bullets(component.accessibility)}

## Content rules

${bullets(component.content)}

## Token references

${component.tokenRefs.map((token) => `- \`${token}\``).join('\n')}

## HTML examples

${examples}

## Authoritative sources

- [Usage guidance](${component.source.guidanceUrl})
- [GOV.UK Frontend ${component.source.govukFrontendVersion} implementation](${component.source.implementationUrl})
`
}

