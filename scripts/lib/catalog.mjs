export function tokenIds(tokens) {
  const ids = []

  function visit(value, path) {
    if (!value || typeof value !== 'object' || Array.isArray(value)) return
    if ('$value' in value) {
      ids.push(path.join('.'))
      return
    }
    for (const [key, child] of Object.entries(value)) {
      if (key.startsWith('$')) continue
      visit(child, [...path, key])
    }
  }

  visit(tokens, [])
  return ids.sort()
}

function cssTokenValue(value) {
  if (typeof value === 'string' || typeof value === 'number') return String(value)
  if (value && typeof value === 'object' && typeof value.value === 'number' && typeof value.unit === 'string') {
    return `${value.value}${value.unit}`
  }
  throw new Error(`Unsupported design token value: ${JSON.stringify(value)}`)
}

export function renderTokenCss(tokens) {
  const entries = []
  const provenance = tokens.$extensions?.['org.govuk-design-md.provenance']
  const reviewedVersion = provenance?.govukFrontendVersion ?? 'unknown'
  const tabletPixels = tokens.govuk?.breakpoint?.tablet?.$value?.value
  const tabletMediaQuery = Number.isFinite(tabletPixels) ? `${tabletPixels / 16}em` : '40.0625em'

  function visit(value, path) {
    if (!value || typeof value !== 'object' || Array.isArray(value)) return
    if ('$value' in value) {
      entries.push([path.join('-'), cssTokenValue(value.$value)])
      return
    }
    for (const [key, child] of Object.entries(value)) {
      if (key.startsWith('$')) continue
      visit(child, [...path, key])
    }
  }

  visit(tokens, [])
  entries.sort(([left], [right]) => left.localeCompare(right, 'en-GB'))

  const functionalColourAliases = [
    ['brand-colour', 'color-brand'],
    ['text-colour', 'color-text'],
    ['secondary-text-colour', 'color-secondary-text'],
    ['body-background-colour', 'color-body-background'],
    ['template-background-colour', 'color-template-background'],
    ['surface-background-colour', 'color-surface-background'],
    ['surface-text-colour', 'color-surface-text'],
    ['surface-border-colour', 'color-surface-border'],
    ['border-colour', 'color-border'],
    ['input-border-colour', 'color-input-border'],
    ['hover-colour', 'color-hover'],
    ['link-colour', 'color-link'],
    ['link-hover-colour', 'color-link-hover'],
    ['link-visited-colour', 'color-link-visited'],
    ['link-active-colour', 'color-link-active'],
    ['focus-colour', 'color-focus'],
    ['focus-text-colour', 'color-focus-text'],
    ['error-colour', 'color-error'],
    ['success-colour', 'color-success']
  ]

  const declarations = entries.map(([id, value]) => `  --${id}: ${value};`)
  declarations.push('')
  declarations.push('  /* Familiar aliases for GOV.UK functional settings. */')
  for (const [alias, target] of functionalColourAliases) {
    declarations.push(`  --govuk-${alias}: var(--govuk-${target});`)
  }
  declarations.push('  --govuk-page-width: var(--govuk-layout-page-width);')
  declarations.push('  --govuk-page-gutter: var(--govuk-layout-gutter-half);')
  declarations.push('  --govuk-border-width: var(--govuk-border-standard);')
  declarations.push('  --govuk-border-width-wide: var(--govuk-border-wide);')
  declarations.push('  --govuk-border-width-narrow: var(--govuk-border-narrow);')
  declarations.push('  --govuk-border-width-form-element: var(--govuk-border-form-element);')
  declarations.push('  --govuk-focus-width: var(--govuk-border-focus);')

  for (const point of [0, 1, 2, 3]) {
    declarations.push(`  --govuk-spacing-responsive-${point}: var(--govuk-spacing-static-${point});`)
  }
  for (const point of [4, 5, 6, 7, 8, 9]) {
    declarations.push(`  --govuk-spacing-responsive-${point}: var(--govuk-spacing-responsive-${point}-mobile);`)
  }
  for (const point of [16, 19, 24, 27, 36, 48, 80]) {
    declarations.push(`  --govuk-font-size-${point}: var(--govuk-typography-scale-${point}-mobile-font-size);`)
    declarations.push(`  --govuk-line-height-${point}: var(--govuk-typography-scale-${point}-mobile-line-height);`)
  }

  const responsiveDeclarations = [
    '    --govuk-page-gutter: var(--govuk-layout-gutter);',
    ...[4, 5, 6, 7, 8, 9].map((point) => `    --govuk-spacing-responsive-${point}: var(--govuk-spacing-responsive-${point}-tablet);`),
    ...[16, 19, 24, 27, 36, 48, 80].flatMap((point) => [
      `    --govuk-font-size-${point}: var(--govuk-typography-scale-${point}-tablet-font-size);`,
      `    --govuk-line-height-${point}: var(--govuk-typography-scale-${point}-tablet-line-height);`
    ])
  ]

  return `/*
 * Generated from the reviewed GOV.UK Frontend ${reviewedVersion} token source.
 * This file does not include component CSS, GDS Transport, or identity assets.
 * Custom properties aid interoperability; GOV.UK Frontend remains authoritative.
 */
:root {
${declarations.join('\n')}
}

@media (min-width: ${tabletMediaQuery}) {
  :root {
${responsiveDeclarations.join('\n')}
  }
}
`
}

function bullets(items) {
  return items.map((item) => `- ${item}`).join('\n')
}

function inlineCodeList(items) {
  return items.length === 0 ? 'None' : items.map((item) => `\`${item}\``).join(', ')
}

const aiManagedBlockStart = '<!-- govuk-design-md:start -->'
const aiManagedBlockEnd = '<!-- govuk-design-md:end -->'

function aiRouterBody() {
  return `## GOV.UK Design System work

When a task creates or changes a GOV.UK-style user interface:

- Read \`DESIGN.md\` or \`GOVUK-DESIGN.md\`, then read user-owned \`DESIGN.local.md\` if present and use \`design/govuk/catalog.json\` to open only the relevant focused records.
- Preserve official semantic HTML, GOV.UK classes, content rules, accessibility relationships and progressive enhancement.
- Use an available framework adapter; otherwise translate syntax without changing the canonical DOM or behaviour.
- Do not infer GOV.UK conformance from visual similarity, tokens or a Tailwind, shadcn or Chakra theme.
- Do not introduce GDS Transport or GOV.UK identity assets unless the service is eligible to use them.`
}

